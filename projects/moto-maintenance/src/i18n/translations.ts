export type TranslationKey = keyof typeof translations.en;

export function t(language: Language, key: TranslationKey, vars?: TranslationVars): string {
  const table = translations[language] as Record<string, string>;
  const fallback = translations.en as Record<string, string>;
  let value = table[key] ?? fallback[key] ?? key;
  if (vars) {
    for (const [name, raw] of Object.entries(vars)) {
      value = value.split(`{${name}}`).join(String(raw));
    }
  }
  return value;
}

export function localeFor(language: Language): string {
  return language === 'sk' ? 'sk-SK' : 'en-GB';
}

export function pluralKey(language: Language, count: number, base: 'interval.every.days' | 'interval.every.months' | 'interval.every.years' | 'unit.days'): TranslationKey {
  const abs = Math.abs(count);
  if (language === 'sk') {
    if (abs === 1) return `${base}.one` as TranslationKey;
    if (abs >= 2 && abs <= 4) return `${base}.few` as TranslationKey;
    return `${base}.other` as TranslationKey;
  }
  return (abs === 1 ? `${base}.one` : `${base}.other`) as TranslationKey;
}
